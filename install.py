def run_uninstall(ui: UI, log) -> int:
    found = find_games()
    if not found:
        manual = ui.pick_dir("Select the MGS game folder to un-mod")
        if not manual:
            ui.error("No install selected. Aborting.")
            return 1
        d = Path(manual)
        for key, g in GAMES.items():
            if (d / g["exe"]).is_file():
                found[key] = (d, Path.home())
        if not found:
            ui.error(f"No Master Collection game executable found in:\n{d}")
            return 1

    # Only offer games this kit actually touched (they have a manifest or the
    # legacy .asi worth clearing).
    modded = {k: v for k, v in found.items()
              if (v[0] / MODKIT_DIRNAME / MANIFEST_NAME).is_file()
              or any((v[0] / n).is_file() for n in LEGACY_M2FIX_FILES)}
    if not modded:
        ui.info("Nothing to uninstall — none of the detected games has a "
                "mgs-modkit manifest from this installer.")
        return 0

    if len(modded) > 1:
        picks = ui.checklist(
            "MGS Mod Kit — Uninstall",
            "Remove this kit's mods from:",
            [(k, f"{GAMES[k]['name']}  ({modded[k][0]})", True)
             for k in modded],
        )
        if not picks:
            ui.error("Nothing selected. Aborting.")
            return 1
        modded = {k: v for k, v in modded.items() if k in picks}

    names = ", ".join(GAMES[k]["short"] for k in modded)
    if not ui.yesno(
        f"Uninstall this kit's mods from {names}?\n\n"
        "Files this kit added will be removed and any originals it backed up "
        "restored. Your game saves are untouched.\n\n"
        "Make sure THE GAMES AND STEAM'S DOWNLOADS ARE CLOSED. Proceed?"
    ):
        return 0

    all_ok = True
    for key in modded:
        g, (game_dir, _) = GAMES[key], modded[key]
        log(f"\n=== Uninstalling {g['name']} ===")
        notes, ok = uninstall_game(game_dir, log)
        all_ok = all_ok and ok
        for note in notes:
            log(f"    • {note}")

    if not all_ok:
        ui.error(
            f"{names}: uninstall finished with problems — some files could "
            "not be removed or restored, so the mgs-modkit backup/manifest "
            "folder was kept for a retry.\n\n"
            "Close the games and Steam's downloads, then run --uninstall "
            "again, or use Steam → Properties → Installed Files → Verify "
            "integrity of game files to reset to stock.")
        return 1

    ui.info(
        f"✅ {names} un-modded.\n\n"
        "Remove the leftover Steam Launch Options too: right-click each game "
        "in Steam → Properties → General → Launch Options and clear the "
        "WINEDLLOVERRIDES line.\n\n"
        "MGSHDFix also writes a logs/ folder and steam_appid.txt at runtime; "
        "delete those if you want a spotless folder, or just run Steam → "
        "Verify integrity of game files.")
    return 0


# ---------------------------------------------------------------------------
# Main flow
# ---------------------------------------------------------------------------
def main() -> int:
    ui = UI()
    logs: list[str] = []

    import argparse
    ap = argparse.ArgumentParser(add_help=False)
    ap.add_argument("--desktop", default=None,
                    help="Path of the launching .desktop shortcut (internal).")
    ap.add_argument("--uninstall", action="store_true",
                    help="Reverse a previous install (restore backups, remove "
                         "added files) instead of installing.")
    cli, _ = ap.parse_known_args()
    desktop = normalize_desktop_path(cli.desktop)

    def log(msg: str) -> None:
        print(msg)
        logs.append(msg)

    if cli.uninstall:
        return run_uninstall(ui, log)

    if not shutil.which("bsdtar"):
        ui.error("`bsdtar` is required but not found. On SteamOS it is "
                 "preinstalled; otherwise install libarchive/bsdtar and re-run.")
        return 1

    # 1. Find the games -----------------------------------------------------
    found = find_games()
    if not found:
        ui.info("Couldn't auto-detect any Master Collection game "
                "(MGS1, MGS2 or MGS3).\n\n"
                "Next you'll be asked to point at a game folder manually "
                "(the one containing 'METAL GEAR SOLID.exe', "
                "'METAL GEAR SOLID2.exe' or 'METAL GEAR SOLID3.exe').")
        manual = ui.pick_dir("Select your MGS1, MGS2 or MGS3 folder")
        if not manual:
            ui.error("No install selected. Aborting.")
            return 1
        d = Path(manual)
        for key, g in GAMES.items():
            if (d / g["exe"]).is_file():
                found[key] = (d, next(iter(steam_roots()),
                                      Path.home() / ".local/share/Steam"))
        if not found:
            ui.error("No Master Collection game executable (METAL GEAR "
                     "SOLID.exe / SOLID2.exe / SOLID3.exe) was found in:\n"
                     f"{d}")
            return 1

    # 2. Which games to process --------------------------------------------
    if len(found) > 1:
        picks = ui.checklist(
            "MGS Mod Kit — Choose Games",
            f"{len(found)} Master Collection games detected. "
            "Install mods for:",
            [(k, f"{GAMES[k]['name']}  ({found[k][0]})", True) for k in found],
        )
        if not picks:
            ui.error("No games selected. Aborting.")
            return 1
        found = {k: v for k, v in found.items() if k in picks}

    # 3. Options -----------------------------------------------------------
    # skip_launcher / update_check apply to BOTH the MGSHDFix games and MGS1
    # (MGSM2Fix), so they're offered whenever any game is selected — an
    # MGS1-only install must not silently inherit the defaults with no say.
    hdfix_sel = [k for k in found if GAMES[k].get("kind", "hdfix") == "hdfix"]
    m2fix_sel = [k for k in found if GAMES[k].get("kind") == "m2fix"]
    device = detect_device()
    opts = {
        "device": device,
        "button_icons": "Steam Deck", "audio_mode": "Stereo (2.0)",
        "hq_movies": True, "skip_splash": True,
        "update_check": False, "skip_launcher": True,
    }
    if hdfix_sel:
        # Detection only reorders the menu so the likeliest choice is
        # preselected — every option stays available on every device.
        icon_items = [
            ("Steam Deck", "Steam Deck — matches the Deck's physical buttons"),
            ("Xbox One", "Xbox — Steam Machine / Xbox-style pads"),
            ("PlayStation 5", "PlayStation 5 — for a DualSense"),
            ("PlayStation 2", "PlayStation 2 — authentic, restored by the Bugfix mod"),
            ("Keyboard / Mouse", "Keyboard / Mouse"),
        ]
        if device != "steam_deck":
            icon_items.insert(0, icon_items.pop(1))    # Xbox first
        opts["button_icons"] = ui.menu(
            "Controller Button Icons",
            "Which button prompts should MGS2/MGS3 show?",
            icon_items,
        ) or icon_items[0][0]

        opts["audio_mode"] = ui.menu(
            "Audio Output",
            "How are you listening?",
            [("Stereo (2.0)", "Stereo — handheld, headphones, TV speakers "
                              "(right for most setups, incl. docked)"),
             ("Surround Sound (5.1)", "5.1 Surround — ONLY with a real "
                                      "surround receiver / speaker setup")],
        ) or "Stereo (2.0)"

    # Build the extras checklist from whatever's actually selected.
    # (No MGS3 high-res texture option: Konami's official texture pack can be
    # installed on the Steam Deck but cannot be used in-game, so the kit
    # always leaves HiresoTexture=0.)
    extra_items: list[tuple[str, str, bool]] = []
    if hdfix_sel:
        extra_items += [
            ("hq_movies", "High-quality cinematics  (set for you — no "
                          "launcher trip needed)", True),
            ("skip_splash", "Skip the unskippable KONAMI intro logos", True),
        ]
    if hdfix_sel or m2fix_sel:
        skip_label = ("Boot straight into the games ("
                      + " / ".join(filter(None, [
                          "skip MGS2/3's Konami launcher" if hdfix_sel else "",
                          "MGS1 re-boots your last-picked version"
                          if m2fix_sel else ""])) + ")")
        extra_items += [
            ("skip_launcher", skip_label, True),
            ("update_check", "Check for mod updates on launch", False),
        ]
    if extra_items:
        extras = ui.checklist(
            "Extra Options", "Optional tweaks (recommended defaults shown):",
            extra_items,
        )
        # None == the user cancelled the dialog: keep the recommended
        # defaults rather than reading a cancel as "turn everything off".
        if extras is not None:
            for tag, _, _ in extra_items:
                opts[tag] = tag in extras

    # 4. Better Audio Mod — one checklist, then explicit per-archive picking.
    audio_archives = collect_audio_archives(ui, hdfix_sel)

    # 5. Confirm ------------------------------------------------------------
    plan = []
    for key in found:
        g, (d, _) = GAMES[key], found[key]
        if g.get("kind", "hdfix") == "m2fix":
            bits = [f"MGSM2Fix {M2FIX_VERSION} (vanilla defaults)"]
        else:
            bits = [f"MGSHDFix {HDFIX_VERSION}"]
            if key in audio_archives:
                bits.append("Better Audio ["
                            + ", ".join(c["status"] for c in audio_archives[key])
                            + "]")
            bits.append(f"Bugfix Compilation {g['bugfix_version']} (Base)")
            bits.append("tuned MGSHDFix.settings")
        plan.append(f"• {g['short']}  →  {d}\n    {' + '.join(bits)}")

    target_dir = next(iter(found.values()))[0]
    summary = (
        f"Device: {'Steam Deck (detected)' if device == 'steam_deck' else 'Linux / SteamOS PC'}"
        f"    Free space: {free_gb(target_dir):.0f} GB\n\n")
    if hdfix_sel:
        summary = (
            f"Button icons: {opts['button_icons']}    "
            f"Audio: {opts['audio_mode']}\n"
            f"Skip logos: {'yes' if opts['skip_splash'] else 'no'}    "
            f"Skip launcher: {'yes' if opts['skip_launcher'] else 'no'}\n\n"
            + summary)
    audio_block = audio_status_text(audio_archives)
    if audio_block:
        summary += "Better Audio components:\n" + audio_block + "\n\n"
        note = audio_recommendation_note(audio_archives)
        if note:
            summary += note + "\n\n"
    elif hdfix_sel:
        summary += "Better Audio: skipped\n\n"
    if not ui.yesno(
        "Ready to install:\n\n" + "\n".join(plan) + "\n\n" + summary +
        "Make sure THE GAMES AND STEAM'S DOWNLOADS ARE CLOSED. Proceed?"
    ):
        return 0

    # 6. Do the work --------------------------------------------------------
    # Each game is installed in its own transaction: on any failure that game
    # is rolled back to exactly how it was found (added files removed, backed-up
    # originals restored), so no half-modified install is left behind. Games
    # already committed before the failure stay installed. A progress window
    # tracks the currently-installing game/component and its stage.
    prog = ui.progress("Installing MGS mods", log)
    total = len(found)
    try:
        with tempfile.TemporaryDirectory(prefix="mgskit_") as td:
            tmp = Path(td)
            for i, key in enumerate(found):
                g, (game_dir, sroot) = GAMES[key], found[key]
                log(f"\n=== {g['name']} ===")

                def stage(text: str, frac: float, short=g["short"], idx=i):
                    # Map an in-game 0..1 fraction onto this game's slice.
                    prog.update(f"{short} — {text}", (idx + frac) / total * 100)

                tx = InstallTxn(game_dir, key, log)
                try:
                    stage("Preparing", 0.05)
                    if g.get("kind", "hdfix") == "m2fix":
                        stage("Extracting MGSM2Fix", 0.4)
                        install_m2fix(tx, tmp, opts, log)
                        stage("Verifying", 0.9)
                    else:
                        # Pre-download every networked archive BEFORE touching
                        # the game, so a download failure can't strike after the
                        # large, un-backed-up Better Audio files are overwritten.
                        stage("Downloading mods (verifying checksums)", 0.1)
                        fetch(HDFIX_URL, tmp / f"MGSHDFix_{HDFIX_VERSION}.zip",
                              log, sha256=HDFIX_SHA256)
                        fetch(g["bugfix_url"],
                              tmp / f"{g['short']}_bugfix_base.zip",
                              log, sha256=g.get("bugfix_sha256"))
                        stage("Extracting MGSHDFix", 0.2)
                        install_hdfix(tx, tmp, log)              # 1
                        if key in audio_archives:                # 2
                            def audio_report(status, frac, short=g["short"],
                                             idx=i):
                                # Map audio extraction onto 0.30–0.65 of slice.
                                prog.update(
                                    f"{short} — Extracting {status} audio",
                                    (idx + 0.30 + 0.35 * frac) / total * 100)
                            install_better_audio(tx, audio_archives[key], log,
                                                 report=audio_report)
                        stage("Extracting Bugfix Compilation", 0.7)
                        install_bugfix(tx, g, tmp, log)          # 3
                        stage("Writing config + launcher options", 0.85)
                        write_settings(tx, g, opts, log)
                        set_launcher_options(tx, g, sroot, opts, log)
                        stage("Verifying", 0.95)
                    tx.commit()
                    stage("Complete", 1.0)
                except BaseException:
                    log(f"  ✗ {g['short']} failed — rolling back its changes …")
                    tx.rollback()
                    raise
                for f in tmp.glob("*.zip"):
                    f.unlink(missing_ok=True)
    except CorruptManifestError as e:
        # Nothing was touched — say so, and don't offer rollback advice.
        prog.close()
        ui.error(str(e))
        return 1
    except (urllib.error.URLError, urllib.error.HTTPError, RuntimeError,
            subprocess.CalledProcessError, OSError) as e:
        ui.error(f"Install failed:\n\n{e}\n\n"
                 "The affected game was put back the way it was — files this "
                 "run added were removed and the originals it backed up were "
                 "restored. (A failed repeat install falls back to your "
                 "previous working setup.)\n\n"
                 "The large Better Audio files are too big to back up, so if "
                 "audio had already been written, use Steam → Properties → "
                 "Installed Files → Verify integrity of game files to restore "
                 "them. You can also just run this installer again.")
        return 1
    finally:
        prog.close()

    # 7. Verify -------------------------------------------------------------
    all_problems = []
    for key in found:
        probs = verify_install(GAMES[key], found[key][0])
        if probs:
            all_problems.append(f"{GAMES[key]['short']}: {', '.join(probs)}")
    if all_problems:
        ui.error("Install finished but verification found problems:\n\n"
                 + "\n".join(all_problems))
        return 1

    # 8. Final manual steps -------------------------------------------------
    names = ", ".join(GAMES[k]["short"] for k in found)
    lo_lines = [f"   {GAMES[key]['short']}:  {launch_option_for(key)}"
                for key in ("mgs1", "mgs2", "mgs3") if key in found]

    # Offer to drop a copy-paste reference on the Desktop (recommended).
    saved_path = None
    if ui.yesno(
        "Save the Steam launch options to a text file on your Desktop?\n\n"
        "It's the one manual step, so a copy you can open and paste from "
        "later is handy.\n\n(Recommended: Yes)"
    ):
        saved_path = save_launch_options_file(ui, list(found.keys()), log)
    saved_note = (f"Saved a copy to {saved_path.name} on your Desktop.\n\n"
                  if saved_path else "")

    tips = []
    if hdfix_sel:
        if opts["skip_launcher"]:
            tips.append("• Launcher skipped, HQ cinematics ON. (To restore it: "
                        "Skip Launcher=0 in plugins/MGSHDFix.settings.)")
        else:
            tips.append("• The Konami launcher still shows — options are "
                        "preset, just hit Play.")
        tips.append("• Docked / on a TV at 720p? Properties → Game Resolution "
                    "→ Native.")
        tips.append("• A “missing config key” error later? Run plugins/"
                    "'MGSHDFix Config Tool.exe' → Save and Exit.")
    if any(GAMES[k].get("kind") == "m2fix" for k in found):
        tips.append("• MGS1 first boot: pick METAL GEAR SOLID (US), Max "
                    "resolution, 4:3.")

    ui.info(
        f"✅ Done — {names} modded and verified!\n\n"
        "ONE manual step (Steam reverts script edits, so do it in Steam):\n"
        "right-click each game → Properties → Launch Options, paste its line:\n\n"
        + "\n".join(lo_lines) + "\n\n"
        + saved_note
        + "\n".join(tips)
    )
    offer_self_cleanup(ui, desktop)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\nAborted.")
        sys.exit(130)
